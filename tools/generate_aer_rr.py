"""Generate the four-port round-robin grant logic as a reduced ordered BDD.

The six Boolean inputs are the two next-port bits and four request bits.
Identical subgraphs are shared; nodes with equal branches are eliminated.
The independent priority-loop specification is exhaustively checked by tests.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
VARIABLES = ('next_port[1]', 'next_port[0]', 'requests[3]',
             'requests[2]', 'requests[1]', 'requests[0]')


def grant(mask: int, start: int) -> int:
    for offset in range(4):
        port = (start + offset) % 4
        if mask & (1 << port):
            return 1 << port
    return 0


def generate() -> tuple[str, dict]:
    nodes = []
    unique = {}

    def build(level, values):
        if all(v == values[0] for v in values):
            return int(values[0])
        middle = len(values) // 2
        low = build(level + 1, values[:middle])
        high = build(level + 1, values[middle:])
        if low == high:
            return low
        key = (level, low, high)
        if key not in unique:
            unique[key] = len(nodes) + 2
            nodes.append(key)
        return unique[key]

    roots = [build(0, [bool(grant(code & 15, code >> 4) & (1 << port))
                       for code in range(64)]) for port in range(4)]
    def signal(node):
        return f"1'b{node}" if node < 2 else f'bdd_{node}'
    lines = ['// Generated by python -m tools.generate_aer_rr; do not hand-edit.',
             '// Reduced ordered BDD; variable order is declared by the generator.',
             'module aer_rr_select (input wire [3:0] requests,',
             '    input wire [1:0] next_port, output wire [3:0] grant);']
    for index, (level, low, high) in enumerate(nodes, 2):
        lines.append(f'    wire bdd_{index} = {VARIABLES[level]} ? {signal(high)} : {signal(low)};')
    lines += [f'    assign grant[{port}] = {signal(node)};' for port, node in enumerate(roots)]
    lines.append('endmodule')
    return '\n'.join(lines) + '\n', {'variables': VARIABLES, 'nonterminal_nodes': len(nodes),
                                       'truth_table_rows': 64, 'roots': roots}


if __name__ == '__main__':
    source, metadata = generate()
    (ROOT / 'rtl/aer_rr_select.v').write_text(source, encoding='ascii', newline='\n')
    out = ROOT / 'build/aer'
    out.mkdir(parents=True, exist_ok=True)
    (out / 'bdd_generation.json').write_text(json.dumps(metadata, indent=2) + '\n')
    print(f"Generated four-port grant selector: {metadata['nonterminal_nodes']} BDD nodes, 64 input combinations")
